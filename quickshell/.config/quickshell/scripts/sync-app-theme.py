#!/usr/bin/env python3
"""Themes desktop apps (Qt5, Qt6, KDE and GTK) from the wallpaper colors.

Reads ~/.local/state/wallpaper/theme.json (written by the wallpaper picker; the
static Catppuccin colors are used until one is picked) and writes:
  - ~/.config/qt{5,6}ct/wallpaper-colors.conf      qt5ct/qt6ct's palette (VLC, qBittorrent, …)
  - ~/.local/share/color-schemes/Wallpaper.colors  the same colors as a KDE color scheme
  - ~/.config/kdeglobals                           the scheme's colors merged in; KDE apps
                                                   (Dolphin) apply the scheme named there
  - ~/.config/gtk-{3,4}.0/wallpaper-colors.css     GTK3 (adw-gtk3) and libadwaita colors,
                                                   imported by the gtk.css next to them
"""
import colorsys
import json
import os
from pathlib import Path

home = Path.home()
theme_file = home / ".local/state/wallpaper/theme.json"
qt_palettes = [home / ".config/qt5ct/wallpaper-colors.conf", home / ".config/qt6ct/wallpaper-colors.conf"]
gtk_css = [home / ".config/gtk-3.0/wallpaper-colors.css", home / ".config/gtk-4.0/wallpaper-colors.css"]
scheme_file = home / ".local/share/color-schemes/Wallpaper.colors"
kdeglobals = home / ".config/kdeglobals"

# Same fallbacks as styles/Theme.qml.
theme = {
    "accent": "#cba6f7",
    "secondary": "#89b4fa",
    "accentText": "#11111b",
    "surface": "#313244",
    "border": "#45475a",
    "text": "#cdd6f4",
    "subtle": "#a6adc8",
    "muted": "#9399b2",
}
try:
    theme.update(json.loads(theme_file.read_text()).get("colors", {}))
except (OSError, ValueError):
    pass

# Fixed status colors (Theme.qml), so red still means error.
negative, neutral, positive = "#f38ba8", "#f9e2af", "#a6e3a1"


def to_hsl(hex_color):
    r, g, b = (int(hex_color[i:i + 2], 16) / 255 for i in (1, 3, 5))
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    return h * 360, s, l


def from_hsl(h, s, l):
    r, g, b = colorsys.hls_to_rgb((h % 360) / 360, l, s)
    return "#%02x%02x%02x" % tuple(round(c * 255) for c in (r, g, b))


# Backgrounds and greys take the accent's hue, like kitty's (WallpaperService.kittyTheme).
hue, accent_sat, _ = to_hsl(theme["accent"])
tint = 1 if accent_sat > 0.2 else 0.3


def grey(s, l):
    return from_hsl(hue, s * tint, l)


c = dict(theme)
c.update(
    base=grey(0.22, 0.11),        # file view: kitty's background
    alternate=grey(0.20, 0.135),  # alternating rows
    window=grey(0.20, 0.14),      # toolbar, sidebar, status bar
    header=grey(0.20, 0.12),
    button=theme["surface"],
    light=grey(0.16, 0.38),
    mid=grey(0.18, 0.18),
    dark=grey(0.20, 0.07),
    disabled=grey(0.12, 0.45),
    visited=from_hsl(to_hsl(theme["secondary"])[0], to_hsl(theme["secondary"])[1], 0.62),
)

# ==========================================
# qt6ct palette: QPalette roles in order, active / disabled / inactive
# ==========================================

roles = [
    "text",       # WindowText
    "button",     # Button
    "light",      # Light
    "border",     # Midlight
    "dark",       # Dark
    "mid",        # Mid
    "text",       # Text
    "#ffffff",    # BrightText
    "text",       # ButtonText
    "base",       # Base
    "window",     # Window
    "#000000",    # Shadow
    "accent",     # Highlight
    "accentText",  # HighlightedText
    "secondary",  # Link
    "visited",    # LinkVisited
    "alternate",  # AlternateBase
    "window",     # NoRole
    "surface",    # ToolTipBase
    "text",       # ToolTipText
    "muted",      # PlaceholderText
]


def palette(overrides=None):
    overrides = overrides or {}
    out = []
    for i, role in enumerate(roles):
        value = overrides.get(i, role)
        value = c.get(value, value)
        out.append("#ff" + value[1:])
    return ", ".join(out)


# Disabled: text-like roles fade out, the selection goes grey.
disabled = {0: "disabled", 6: "disabled", 8: "disabled", 12: "border", 13: "disabled"}
qt_palette_text = (
    "# Generated by quickshell/scripts/sync-app-theme.py from the wallpaper colors.\n"
    "[ColorScheme]\n"
    f"active_colors={palette()}\n"
    f"disabled_colors={palette(disabled)}\n"
    f"inactive_colors={palette()}\n"
)

# ==========================================
# KDE color scheme
# ==========================================


def rgb(key):
    value = c.get(key, key)
    return ",".join(str(int(value[i:i + 2], 16)) for i in (1, 3, 5))


def color_group(background, alternate, foreground="text"):
    return {
        "BackgroundNormal": rgb(background),
        "BackgroundAlternate": rgb(alternate),
        "ForegroundNormal": rgb(foreground),
        "ForegroundInactive": rgb("muted"),
        "ForegroundActive": rgb("accent"),
        "ForegroundLink": rgb("secondary"),
        "ForegroundVisited": rgb("visited"),
        "ForegroundNegative": rgb(negative),
        "ForegroundNeutral": rgb(neutral),
        "ForegroundPositive": rgb(positive),
        "DecorationFocus": rgb("accent"),
        "DecorationHover": rgb("accent"),
    }


selection = color_group("accent", "accent", "accentText")
# Text on the accent stays dark, or it would vanish into it.
selection.update(ForegroundInactive=rgb("accentText"), ForegroundActive=rgb("accentText"),
                 ForegroundLink=rgb("accentText"), ForegroundVisited=rgb("accentText"))

scheme = {
    "ColorEffects:Disabled": {
        "Color": "56,56,56", "ColorAmount": "0", "ColorEffect": "0",
        "ContrastAmount": "0.65", "ContrastEffect": "1",
        "IntensityAmount": "0.1", "IntensityEffect": "2",
    },
    "ColorEffects:Inactive": {
        "ChangeSelectionColor": "true", "Color": "112,111,110", "ColorAmount": "0.025",
        "ColorEffect": "2", "ContrastAmount": "0.1", "ContrastEffect": "2", "Enable": "false",
        "IntensityAmount": "0", "IntensityEffect": "0",
    },
    "Colors:Button": color_group("button", "border"),
    "Colors:Complementary": color_group("dark", "window"),
    "Colors:Header": color_group("header", "window"),
    "Colors:Header][Inactive": color_group("header", "window"),
    "Colors:Selection": selection,
    "Colors:Tooltip": color_group("surface", "button"),
    "Colors:View": color_group("base", "alternate"),
    "Colors:Window": color_group("window", "header"),
    "WM": {
        "activeBackground": rgb("header"), "activeBlend": rgb("text"),
        "activeForeground": rgb("text"), "inactiveBackground": rgb("header"),
        "inactiveBlend": rgb("muted"), "inactiveForeground": rgb("muted"),
    },
}


def render(groups):
    return "\n".join(
        f"[{name}]\n" + "".join(f"{k}={v}\n" for k, v in entries.items())
        for name, entries in groups.items()
    )


scheme_text = render({"General": {"ColorScheme": "Wallpaper", "Name": "Wallpaper"}, **scheme})

# ==========================================
# kdeglobals: keep everything else that's in there, replace the color groups
# ==========================================


def read_ini(path):
    groups = {}
    current = None
    try:
        lines = path.read_text().splitlines()
    except OSError:
        lines = []
    for line in lines:
        if line.startswith("[") and line.endswith("]"):
            current = groups.setdefault(line[1:-1], [])
        elif current is not None and line.strip():
            current.append(line)
        elif current is None and line.strip():
            groups.setdefault("", []).append(line)
    return groups


def set_key(lines, key, value, only_if_missing=False):
    for i, line in enumerate(lines):
        if line.split("=", 1)[0].split("[$", 1)[0] == key:
            if not only_if_missing:
                lines[i] = f"{key}={value}"
            return
    lines.append(f"{key}={value}")


groups = read_ini(kdeglobals)
for name in list(groups):
    if name.startswith(("Colors:", "ColorEffects:")) or name == "WM":
        del groups[name]
set_key(groups.setdefault("General", []), "ColorScheme", "Wallpaper")
# KDE apps pick the scheme they apply from [UiSettings] in their own config, which falls
# back to kdeglobals. Without it they choose light or dark Breeze, over qt6ct's palette.
set_key(groups.setdefault("UiSettings", []), "ColorScheme", "Wallpaper")
# Icons: breeze-dark unless you've picked something else.
set_key(groups.setdefault("Icons", []), "Theme", "breeze-dark", only_if_missing=True)
for name, entries in scheme.items():
    groups[name] = [f"{k}={v}" for k, v in entries.items()]

kdeglobals_text = "\n".join(
    (f"[{name}]\n" if name else "") + "".join(line + "\n" for line in lines)
    for name, lines in groups.items()
)


# ==========================================
# GTK: libadwaita's named colors (adw-gtk3 uses the same names in GTK3)
# ==========================================

gtk_colors = {
    "accent_color": "accent",
    "accent_bg_color": "accent",
    "accent_fg_color": "accentText",
    "window_bg_color": "window",
    "window_fg_color": "text",
    "view_bg_color": "base",
    "view_fg_color": "text",
    "headerbar_bg_color": "header",
    "headerbar_fg_color": "text",
    "headerbar_backdrop_color": "window",
    "sidebar_bg_color": "header",
    "sidebar_fg_color": "text",
    "sidebar_backdrop_color": "window",
    "secondary_sidebar_bg_color": "header",
    "secondary_sidebar_fg_color": "text",
    "secondary_sidebar_backdrop_color": "window",
    "dialog_bg_color": "window",
    "dialog_fg_color": "text",
    "popover_bg_color": "surface",
    "popover_fg_color": "text",
    "thumbnail_bg_color": "surface",
    "thumbnail_fg_color": "text",
    # Status colors are pastels, so text on them stays dark.
    "destructive_color": negative,
    "destructive_bg_color": negative,
    "destructive_fg_color": "accentText",
    "error_color": negative,
    "error_bg_color": negative,
    "error_fg_color": "accentText",
    "success_color": positive,
    "success_bg_color": positive,
    "success_fg_color": "accentText",
    "warning_color": neutral,
    "warning_bg_color": neutral,
    "warning_fg_color": "accentText",
}
gtk_header = "/* Generated by quickshell/scripts/sync-app-theme.py from the wallpaper colors. */\n"
gtk3_text = gtk_header + "".join(f"@define-color {k} {c.get(v, v)};\n" for k, v in gtk_colors.items())
# libadwaita 1.8+ reads CSS variables; the named colors cover older versions.
gtk4_text = gtk3_text + ":root {\n" + "".join(
    f"  --{k.replace('_', '-')}: {c.get(v, v)};\n" for k, v in gtk_colors.items()) + "}\n"


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(text)
    os.replace(tmp, path)  # one rename, so watchers (qt6ct) see the whole file


write(scheme_file, scheme_text)
write(kdeglobals, kdeglobals_text)
write(gtk_css[0], gtk3_text)
write(gtk_css[1], gtk4_text)
for path in qt_palettes:
    write(path, qt_palette_text)
